// plane.js - plane rotation and movement handled here

const translate = ([x, y, z], [tx, ty, tz]) => {
    return [x + tx, y + ty, z + tz];
}

const rotate = (v, forward, up, right) => {
    // rotate the vertex v based on the plane's orientation vectors (forward, up, right)
    const [x, y, z] = v;
    return [
        - x * right[0] + y * up[0] + z * forward[0],
        - x * right[1] + y * up[1] + z * forward[1],
        - x * right[2] + y * up[2] + z * forward[2]
    ];
}

